/**
 * Copy self-hosted font files for static assets (e.g. MFM demo) under /fonts/.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "public", "fonts");

const DM_WEIGHTS = [
  { src: "dm-sans-latin-400-normal.woff2", weight: 400, style: "normal" },
  { src: "dm-sans-latin-500-normal.woff2", weight: 500, style: "normal" },
  { src: "dm-sans-latin-600-normal.woff2", weight: 600, style: "normal" },
  { src: "dm-sans-latin-700-normal.woff2", weight: 700, style: "normal" },
  { src: "dm-sans-latin-400-italic.woff2", weight: 400, style: "italic" },
];

const FACULTY_SRC = "faculty-glyphic-latin-400-normal.woff2";

async function copyFile(from, to) {
  await fs.mkdir(path.dirname(to), { recursive: true });
  await fs.copyFile(from, to);
}

async function main() {
  const dmDir = path.join(root, "node_modules", "@fontsource", "dm-sans", "files");
  const facultyFrom = path.join(
    root,
    "node_modules",
    "@fontsource",
    "faculty-glyphic",
    "files",
    FACULTY_SRC,
  );

  await fs.mkdir(outDir, { recursive: true });

  const faces = [];

  for (const w of DM_WEIGHTS) {
    const base = path.basename(w.src);
    await copyFile(path.join(dmDir, w.src), path.join(outDir, base));
    faces.push(
      `@font-face{font-family:"DM Sans";font-style:${w.style};font-weight:${w.weight};font-display:swap;src:url("/fonts/${base}") format("woff2");}`,
    );
  }

  await copyFile(facultyFrom, path.join(outDir, FACULTY_SRC));
  faces.push(
    `@font-face{font-family:"Faculty Glyphic";font-style:normal;font-weight:400;font-display:swap;src:url("/fonts/${FACULTY_SRC}") format("woff2");}`,
  );

  await fs.writeFile(
    path.join(outDir, "site-fonts.css"),
    `/* Self-hosted fonts for static pages (generated by sync-public-fonts.mjs) */\n${faces.join("\n")}\n`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
